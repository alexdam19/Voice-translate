/** Width in pixels of a string in the 3 x 5 font. */
export const miniWidth = (s: string, u = 1): number => (s.length * 4 - 1) * u;

/** Stencilled 3 x 5 text in one colour, with an optional one-pixel shadow. */
export function pxMini(x: CanvasRenderingContext2D, s: string, px: number, py: number, color: string, align: 'left' | 'center' | 'right' = 'left', shadow: string | null = 'rgba(0,0,0,0.7)', u = 1): void {
  const w = miniWidth(s, u);
  const ox = Math.round(align === 'center' ? px - w / 2 : align === 'right' ? px - w : px);
  py = Math.round(py);
  for (const pass of shadow ? [0, 1] : [1]) {
    x.fillStyle = pass ? color : shadow!;
    const d = pass ? 0 : u;
    for (let i = 0; i < s.length; i++) {
      const g = MROWS[s[i]] ?? MROWS[s[i].toUpperCase()] ?? MROWS[' '];
      for (let r = 0; r < 5; r++) for (let c = 0; c < 3; c++) if (g[r][c]) x.fillRect(ox + (i * 4 + c) * u + d, py + r * u + d, u, u);
    }
  }
}
